"""Build the `ipxact:component` document of an entity.

The document follows IEEE Std 1685-2022: the generics are component
parameters and, in the instantiation of the RTL view, module parameters
whose value is the parameter; the ports are wire ports whose vector
limits are expressions of the parameters; the sources of the component
of the manifest are one file set.
"""

from dataclasses import dataclass
from xml.etree.ElementTree import (
    Element,
    SubElement,
    indent,
    register_namespace,
    tostring,
)

from riscv_tools.ipxact.model import Entity, Generic, Port
from riscv_tools.ipxact.vlnv import Vlnv

NAMESPACE = "http://www.accellera.org/XMLSchema/IPXACT/1685-2022"
EXTENSION = "http://insper.edu.br/XMLSchema/insper-riscv"
SCHEMA_LOCATION = f"{NAMESPACE} {NAMESPACE}/index.xsd"
XSI = "http://www.w3.org/2001/XMLSchema-instance"
VIEW = "rtl"
INSTANTIATION = "rtl_instantiation"
FILE_SET = "rtl_sources"
FILE_TYPE = "vhdlSource-2008"
BANNER = (
    "Generated by `riscv-tools ipxact generate` from the VHDL and "
    "`paths.yaml`; do not edit by hand."
)
register_namespace("ipxact", NAMESPACE)
register_namespace("insper", EXTENSION)
register_namespace("xsi", XSI)
FORMATS = {
    "natural": "int",
    "integer": "int",
    "positive": "int",
    "boolean": "bit",
    "string": "string",
    "std_logic": "bit",
    "std_logic_vector": "bit",
}


@dataclass(frozen=True)
class Source:
    """What the document says about where the entity comes from.

    Parameters
    ----------
    vlnv : Vlnv
        The identifier of the component.
    component : str
        The component of the `provides` manifest that lists the file.
    sources : tuple of str
        The files of that component, relative to the repository root.
    requires : tuple of str
        The components it requires, as written in the manifest.
    """

    vlnv: Vlnv
    component: str
    sources: tuple[str, ...]
    requires: tuple[str, ...]


def _q(tag: str) -> str:
    """Qualify a tag with the IP-XACT namespace."""
    return f"{{{NAMESPACE}}}{tag}"


def _text(parent: Element, tag: str, text: str) -> Element:
    """Add a child element that holds text."""
    child = SubElement(parent, _q(tag))
    child.text = text
    return child


def _name_group(parent: Element, name: str, description: str) -> None:
    """Add the name and, if there is one, the description."""
    _text(parent, "name", name)
    if description:
        _text(parent, "description", description)


def _vectors(parent: Element, vectors: tuple[tuple[str, str], ...]) -> None:
    """Add the vectors of a port or parameter."""
    if not vectors:
        return
    container = SubElement(parent, _q("vectors"))
    for left, right in vectors:
        vector = SubElement(container, _q("vector"))
        _text(vector, "left", left)
        _text(vector, "right", right)


def _parameter(parent: Element, generic: Generic) -> None:
    """Add the component parameter of a generic."""
    node = SubElement(parent, _q("parameter"))
    node.set("parameterId", generic.name)
    node.set("resolve", "user")
    node.set("type", FORMATS[generic.vhdl_type])
    if generic.minimum is not None:
        node.set("minimum", str(generic.minimum))
    if generic.maximum is not None:
        node.set("maximum", str(generic.maximum))
    _name_group(node, generic.name, generic.description)
    _vectors(node, generic.vectors)
    _text(node, "value", generic.default or "")


def _module_parameters(parent: Element, generics: tuple[Generic, ...]) -> None:
    """Add the module parameters that bind the generics."""
    if not generics:
        return
    container = SubElement(parent, _q("moduleParameters"))
    for generic in generics:
        node = SubElement(container, _q("moduleParameter"))
        node.set("usageType", "typed")
        node.set("dataType", generic.vhdl_type)
        _name_group(node, generic.name, "")
        _vectors(node, generic.vectors)
        _text(node, "value", generic.name)


def _port(parent: Element, port: Port) -> None:
    """Add one wire port."""
    node = SubElement(parent, _q("port"))
    _name_group(node, port.name, port.description)
    wire = SubElement(node, _q("wire"))
    _text(wire, "direction", port.direction)
    _vectors(wire, port.vectors)
    defs = SubElement(wire, _q("wireTypeDefs"))
    definition = SubElement(defs, _q("wireTypeDef"))
    _text(definition, "typeName", port.type_name)
    if port.type_definition:
        _text(definition, "typeDefinition", port.type_definition)
    _text(definition, "viewRef", VIEW)


def _model(parent: Element, entity: Entity) -> None:
    """Add the view, the instantiation and the ports."""
    model = SubElement(parent, _q("model"))
    views = SubElement(model, _q("views"))
    view = SubElement(views, _q("view"))
    _text(view, "name", VIEW)
    _text(view, "envIdentifier", "VHDL:*:*")
    _text(view, "componentInstantiationRef", INSTANTIATION)
    container = SubElement(model, _q("instantiations"))
    node = SubElement(container, _q("componentInstantiation"))
    _text(node, "name", INSTANTIATION)
    _text(node, "language", "vhdl").set("strict", "true")
    _text(node, "libraryName", "work")
    _text(node, "moduleName", entity.name)
    _module_parameters(node, entity.generics)
    reference = SubElement(node, _q("fileSetRef"))
    _text(reference, "localName", FILE_SET)
    if entity.ports:
        ports = SubElement(model, _q("ports"))
        for port in entity.ports:
            _port(ports, port)


def _file_sets(parent: Element, sources: tuple[str, ...]) -> None:
    """Add the file set with the sources of the component."""
    container = SubElement(parent, _q("fileSets"))
    node = SubElement(container, _q("fileSet"))
    _text(node, "name", FILE_SET)
    for path in sources:
        item = SubElement(node, _q("file"))
        _text(item, "name", path)
        _text(item, "fileType", FILE_TYPE)
        _text(item, "logicalName", "work")


def _extensions(parent: Element, source: Source) -> None:
    """Add the project data the standard has no element for."""
    container = SubElement(parent, _q("vendorExtensions"))
    node = SubElement(container, f"{{{EXTENSION}}}provides")
    node.set("component", source.component)
    for name in source.requires:
        SubElement(node, f"{{{EXTENSION}}}requires").text = name


def build(entity: Entity, source: Source) -> Element:
    """Build the component document of an entity.

    Parameters
    ----------
    entity : Entity
        The entity read from the VHDL.
    source : Source
        The identifier and the origin of the component.

    Returns
    -------
    Element
        The `ipxact:component` element.
    """
    root = Element(_q("component"))
    root.set(f"{{{XSI}}}schemaLocation", SCHEMA_LOCATION)
    vlnv = source.vlnv
    _text(root, "vendor", vlnv.vendor)
    _text(root, "library", vlnv.library)
    _text(root, "name", vlnv.name)
    _text(root, "version", vlnv.version)
    if entity.description:
        _text(root, "description", entity.description)
    _model(root, entity)
    _file_sets(root, source.sources)
    if entity.generics:
        parameters = SubElement(root, _q("parameters"))
        for generic in entity.generics:
            _parameter(parameters, generic)
    _extensions(root, source)
    return root


def serialize(root: Element) -> str:
    """Write a document as indented XML text.

    Parameters
    ----------
    root : Element
        The document root.

    Returns
    -------
    str
        The text, with the XML declaration and the banner comment.
    """
    indent(root, space="  ")
    body = tostring(root, encoding="unicode")
    return (
        f'<?xml version="1.0" encoding="UTF-8"?>\n<!-- {BANNER} -->\n{body}\n'
    )
