"""Write a platform config for the project that consumes it.

A platform keeps its `config.yaml` with every path written from the
root of the repository that owns it. A project that runs tests on the
platform (Tests, Certification) has the platform repository as a
submodule, so the same paths start one folder deeper there. This
module reads the platform config with its `extends:` chain resolved,
puts the folder of the submodule in front of every path the platform
owns, and writes one standalone file. The paths the consumer owns
(`paths.include_dir`, `paths.build_dir`, `paths.c_dir` and
`paths.asm_dir`) are left alone, and a variant config of the consumer
extends the written file.

The keys the platform owns are in `PATH_KEYS`.
"""

import copy
from pathlib import Path, PurePosixPath
from typing import Any, cast

import yaml

from riscv_tools.config_files import read_config

PATH_KEYS: tuple[tuple[str, ...], ...] = (
    ("toolchain", "specs"),
    ("paths", "boot_memory"),
    ("paths", "boot_memory_linker_script"),
    ("paths", "nor_programmer"),
    ("paths", "sources"),
    ("emulator", "sources"),
    ("quartus", "project_dir"),
    ("quartus", "generate", "platform"),
    ("quartus", "generate", "out"),
    ("quartus", "generate", "boards_dir"),
    ("quartus", "generate", "chips_dir"),
    ("sim", "vhdl_sources"),
    ("sim", "python_path"),
)

_HEADER = """\
# Generated by `riscv-tools platform sync` from {source}.
# Do not edit by hand: change the platform config and run the command again.
# The paths of the platform start with `{prefix}/`, its submodule folder.
"""


def flatten(config: Path) -> dict[str, Any]:
    """Read a platform config with its `extends:` chain resolved.

    Parameters
    ----------
    config : Path
        The `config.yaml` of the platform.

    Returns
    -------
    dict of str to Any
        The config merged over its bases, without the `extends` key.
    """
    return read_config(config)


def _prefixed(prefix: str, value: str) -> str:
    """Put the folder of the submodule in front of one path.

    Parameters
    ----------
    prefix : str
        The folder of the platform repository in the consumer.
    value : str
        One path from the platform config.

    Returns
    -------
    str
        The path from the root of the consumer; an absolute one is kept.
    """
    path = PurePosixPath(value)
    if path.is_absolute():
        return value
    return str(PurePosixPath(prefix) / path)


def _parent_of(
    config: dict[str, Any], keys: tuple[str, ...]
) -> dict[str, Any] | None:
    """Find the dict that holds the last key of a path, if there is one.

    Parameters
    ----------
    config : dict of str to Any
        The config to look in.
    keys : tuple of str
        The key path, from the top.

    Returns
    -------
    dict of str to Any or None
        The dict that holds `keys[-1]`, or None when a level is missing.
    """
    node: Any = config
    for key in keys[:-1]:
        if not isinstance(node, dict):
            return None
        node = cast("dict[str, Any]", node).get(key)
    return cast("dict[str, Any]", node) if isinstance(node, dict) else None


def _rebased_value(prefix: str, value: Any) -> Any:
    """Put the submodule folder in front of a path or a list of them.

    Parameters
    ----------
    prefix : str
        The folder of the platform repository in the consumer.
    value : Any
        What the config holds under a path key.

    Returns
    -------
    Any
        The path, or each path of the list, from the root of the
        consumer; anything that is not a path is returned as it is.
    """
    if isinstance(value, str):
        return _prefixed(prefix, value)
    if isinstance(value, list):
        return [
            _rebased_value(prefix, item) for item in cast("list[Any]", value)
        ]
    return value


def rebase(config: dict[str, Any], prefix: str) -> dict[str, Any]:
    """Put the folder of the submodule in front of the platform's paths.

    Parameters
    ----------
    config : dict of str to Any
        The flattened platform config.
    prefix : str
        The folder of the platform repository in the consumer, such as
        `Insper-RISC-V`.

    Returns
    -------
    dict of str to Any
        A new config; `config` is not changed.
    """
    result = copy.deepcopy(config)
    for keys in PATH_KEYS:
        parent = _parent_of(result, keys)
        if parent is not None and keys[-1] in parent:
            parent[keys[-1]] = _rebased_value(prefix, parent[keys[-1]])
    return result


def render(config: dict[str, Any], source: str, prefix: str) -> str:
    """Format a rebased config as the text of the written file.

    Parameters
    ----------
    config : dict of str to Any
        The rebased config.
    source : str
        The platform config it came from, for the header.
    prefix : str
        The folder of the platform repository in the consumer.

    Returns
    -------
    str
        The header and the YAML, ending in a newline.
    """
    body = yaml.safe_dump(
        config, sort_keys=False, default_flow_style=False, width=1000
    )
    return _HEADER.format(source=source, prefix=prefix) + body


def check_output(output: Path, text: str) -> list[str]:
    """Compare the file on disk with what the command would write.

    Parameters
    ----------
    output : Path
        The file the command writes.
    text : str
        What the command would write.

    Returns
    -------
    list of str
        One problem when the file is missing or differs, else empty.
    """
    if not output.is_file():
        return [f"{output}: missing, run `riscv-tools platform sync`"]
    if output.read_text() != text:
        return [f"{output}: differs, run `riscv-tools platform sync`"]
    return []


def write_output(output: Path, text: str) -> None:
    """Write the file, creating the folders above it.

    Parameters
    ----------
    output : Path
        The file to write.
    text : str
        Its content.
    """
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text)
