"""The header that tells the boot memory which extensions the core has.

The boot memory is assembled from one fragment per extension, and a
`.S` file picks the fragments with the preprocessor. The header is
generated from the `core` block of the platform, so no switch is typed
twice:

```yaml
generate:
  boot_config_h:
    path: runtime/boot_config.h
```

It holds one `RV32_HAS_<EXTENSION>` per extension and extra of the
block (1 when the core has it, 0 when it does not), `RV32_IS_E` for the
base E and `RV32_TEST_WAIT`. `Zicntr` and `Zihpm` imply `Zicsr`, so
`RV32_HAS_ZICSR` is 1 with either. `M` does not turn on
`RV32_HAS_ZMMUL`, which follows `Zmmul` alone, as the `HAS_ZMMUL` of the
`config_pkg` does.

`RV32_TEST_WAIT` separates the two builds of the boot memory. With
`boot.wait_restart` it is 1: the boot memory is the one of the tests,
which keeps the wait point that a finished test jumps to, fixed at that
address. Without the key it is 0: the boot memory is the one of an
application, and the wait point is not assembled.
"""

import re
from typing import Any

from riscv_tools.memory_map.core import platform_dict
from riscv_tools.memory_map.core_profile import EXTRAS, KNOWN
from riscv_tools.memory_map.march import extension_names, platform_core

# Todas as extensões e extras que o bloco `core` aceita, na ordem em que
# o cabeçalho as escreve.
FLAGGED = (*KNOWN, *EXTRAS)

_HEADER = """\
/* Generated by `riscv-tools generate-memory-map` from {source}.
 * Do not edit by hand: change the platform YAML and run it again.
 *
 * Which extensions the core has, for the fragments of the boot memory
 * (a .S file includes it too). RV32_TEST_WAIT is 1 when the platform has
 * boot.wait_restart: the boot memory of the tests, with the wait point
 * that a finished test jumps to. */

#ifndef RV32_BOOT_CONFIG_H
#define RV32_BOOT_CONFIG_H

{defines}
#endif
"""


def macro_of(name: str) -> str:
    """Name the macro of an extension.

    Parameters
    ----------
    name : str
        The canonical name, such as `Zicsr` or `AccessFaults`.

    Returns
    -------
    str
        `RV32_HAS_ZICSR`, `RV32_HAS_ACCESS_FAULTS`.
    """
    return "RV32_HAS_" + re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


def flags_of(core: dict[str, Any]) -> dict[str, bool]:
    """Say which extensions a `core` block turns on.

    Parameters
    ----------
    core : dict of {str: Any}
        The `core` block, with the extras in `extensions`.

    Returns
    -------
    dict of {str: bool}
        Each name of `FLAGGED`; `Zicsr` is on when `Zicntr` or `Zihpm`
        is, which imply it.
    """
    listed = extension_names(core)
    return {name: name.lower() in listed for name in FLAGGED}


def render_boot_config(platform: dict[str, Any], source: str) -> str:
    """Render the header with the extensions of the core.

    Parameters
    ----------
    platform : dict of {str: Any}
        The loaded platform.
    source : str
        The platform file, for the header.

    Returns
    -------
    str
        The file: `RV32_HAS_*` for each extension, `RV32_IS_E` and
        `RV32_TEST_WAIT`.
    """
    core = platform_core(platform)
    values = {
        macro_of(name): int(flag) for name, flag in flags_of(core).items()
    }
    values["RV32_IS_E"] = int(core["base"] == "E")
    values["RV32_TEST_WAIT"] = int(
        "wait_restart" in platform_dict(platform, "boot")
    )
    defines = "\n".join(
        f"#define {macro} {value}" for macro, value in values.items()
    )
    return _HEADER.format(source=source, defines=defines)
