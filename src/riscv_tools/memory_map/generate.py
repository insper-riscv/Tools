"""Write the files that carry a platform's memory map.

The platform YAML is the source of truth for the map. Under `generate`
it names the files to write from it, so no copy of the map is typed by
hand: the linker flags of the test programs (a GCC specs file), the
linker script of the boot memory, a C and assembly header with the
addresses of the words the host shares with the program, and a VHDL
package with the generics of the core, the base of every peripheral
and the tables of windows that the interconnect decodes, and the
`config_pkg` with the constants of the platform (see
`riscv_tools.memory_map.config_pkg`).

```yaml
generate:
  specs:
    path: runtime/rv32im-fpga.specs
    rom: FLASH
    ram: RAM
    ram_limit: stdout
  boot_ld:
    path: runtime/boot_memory.ld
  runtime:
    path: runtime/memory_map.h
    ram: RAM
  syscalls:
    path: runtime/syscalls.c
  vhdl:
    path: rtl/map_pkg.vhd
    package: map_pkg
    rom: FLASH
    ram: RAM
    rom_external: false
    ram_external: false
  config_pkg:
    path: rtl/config_pkg.vhd
  platform_h:
    path: tools/riscv_build/include-demo/rv32_platform.h
  bank_specs:
    - {path: runtime/bank-b.specs, rom: BANK_B_PAYLOAD, ram: RAM}
  banks_h:
    path: runtime/flash_banks.h
```

`bank_specs` lists specs files like `specs`, each linking a program for
a FLASH bank (see `riscv_tools.memory_map.banks`), and `banks_h` is the
header with the banks and the layout of the image.

`check` compares the written files with what would be generated, so a
change of the map without a new generation fails.
"""

