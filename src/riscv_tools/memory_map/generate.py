"""Write the files that carry a platform's memory map.

The platform YAML is the source of truth for the map. Under `generate`
it names the files to write from it, so no copy of the map is typed by
hand: the linker flags of the test programs (a GCC specs file), the
linker script of the boot ROM, a C and assembly header with the
addresses of the words the host shares with the program, and a VHDL
package with the generics of the core and the base of every
peripheral.

```yaml
generate:
  specs:
    path: runtime/rv32im-fpga.specs
    rom: FLASH
    ram: RAM
    ram_limit: stdout
  boot_ld:
    path: runtime/boot_rom.ld
  runtime:
    path: runtime/memory_map.h
    ram: RAM
  vhdl:
    path: rtl/map_pkg.vhd
    package: map_pkg
    rom: FLASH
    ram: RAM
    rom_external: false
    ram_external: false
    ext_base: 0x40000000
    periph_base: 0x80000000
```

`check` compares the written files with what would be generated, so a
change of the map without a new generation fails.
"""

from pathlib import Path
from typing import Any, cast

from riscv_tools.memory_map import memory as memory_choice
from riscv_tools.memory_map.core import (
    PERIPHERAL_WINDOW_BASE,
    Mismatch,
    load_platform,
    platform_dict,
    platform_list,
    symbols,
)
from riscv_tools.memory_map.expressions import evaluate
from riscv_tools.memory_map.profile import SWITCHES, resolve
from riscv_tools.memory_map.validation import validate_platform

KIB = 1024
PAGE = 4096

_SPECS = "\n".join(
    [
        "# Generated by `riscv-tools generate-memory-map` from {source}.",
        "# Do not edit by hand: change the platform YAML and run it again.",
        "%include <picolibc.specs>",
        "%rename link rv32imfpga_picolibc_link",
        "",
        "*link:",
        "%(rv32imfpga_picolibc_link)"
        " --defsym=__flash={rom_base} --defsym=__flash_size={rom_size}"
        " --defsym=__ram={ram_base} --defsym=__ram_size={ram_size}"
        " %{{!DRV32_SPIKE:--defsym=rv32_wait_restart={wait_restart}}}",
        "",
        "*startfile:",
        "crt0-hosted%O%s",
        "",
    ]
)

_BOOT_LD = "\n".join(
    [
        "/* Generated by `riscv-tools generate-memory-map` from {source}.",
        " * Do not edit by hand: change the platform YAML and run it again.",
        " *",
        " * Linker script for boot_rom.S, the fixed bootloader. It is built",
        " * and written once; rv32_wait_restart is pinned to a fixed address",
        " * that the images of the tests reach as an absolute symbol.",
        " */",
        "",
        "MEMORY",
        "{{",
        "  boot_rom (rx) : ORIGIN = {origin}, LENGTH = {length}",
        "}}",
        "",
        "RESET_RESERVED = {wait_restart};",
        "",
        'OUTPUT_ARCH("riscv")',
        "ENTRY(_reset)",
        "",
        "SECTIONS",
        "{{",
        "  .text.reset {origin} : {{ *(.text.reset) }} > boot_rom",
        "  ASSERT(SIZEOF(.text.reset) <= RESET_RESERVED,",
        '         "boot_rom.S: _reset grew past RESET_RESERVED")',
        "",
        "  .text.wait_restart RESET_RESERVED :",
        "    {{ *(.text.wait_restart) }} > boot_rom",
        "",
        "  . = ALIGN(4);",
        "  ASSERT(. <= ORIGIN(boot_rom) + LENGTH(boot_rom),",
        '         "boot_rom.S exceeds the BOOT_ROM")',
        "}}",
        "",
    ]
)

_RUNTIME = """\
/* Generated by `riscv-tools generate-memory-map` from {source}.
 * Do not edit by hand: change the platform YAML and run it again.
 *
 * The addresses of the words the host shares with the program, for the
 * runtime in C and in assembly (a .S file includes it too). */

#ifndef RV32_MEMORY_MAP_H
#define RV32_MEMORY_MAP_H

#ifdef __ASSEMBLER__
#define RV32_ADDRESS(value) value
#else
#define RV32_ADDRESS(value) value##u
#endif

{defines}
#endif
"""

_VHDL = """\
-- ===========================================================================
-- Mapa de memória da plataforma, gerado por
-- `riscv-tools generate-memory-map` a partir de {source}.
--
-- Não edite à mão: mude o YAML da plataforma e rode o comando de novo. Os
-- limites estão em KiB, como os genéricos do núcleo, e os endereços dos
-- periféricos em bytes.
-- ===========================================================================

library ieee;
use ieee.std_logic_1164.all;

package {package} is

{profile}\t-- Expoente do tamanho da BOOT_ROM, que ocupa [0, 2**BOOT_ROM_BITS).
\tconstant BOOT_ROM_BITS       : natural  := {boot_bits};
\t-- Tamanho da BOOT_ROM, em bytes.
\tconstant BOOT_ROM_SIZE_BYTES : positive := {boot_bytes};
\t-- Base da ROM, em KiB, logo depois da BOOT_ROM.
\tconstant ROM_BASE_KIB        : natural  := {rom_base};
\t-- Fim exclusivo da ROM, em KiB.
\tconstant ROM_END_KIB         : natural  := {rom_end};
\t-- Armazenamento da ROM, em bytes: a menor potência de dois que cobre
\t-- [0, fim da ROM).
\tconstant ROM_STORAGE_BYTES   : positive := {rom_storage};
{rom_external}\t-- Base da RAM, em KiB.
\tconstant RAM_BASE_KIB        : natural  := {ram_base};
\t-- Fim exclusivo da RAM, em KiB.
\tconstant RAM_END_KIB         : natural  := {ram_end};
\t-- Armazenamento da RAM, em bytes: a menor potência de dois que cobre
\t-- o tamanho da RAM.
\tconstant RAM_STORAGE_BYTES   : positive := {ram_storage};
\t-- Página de 4 KiB no topo da RAM (bits 31:12 do endereço), onde ficam as
\t-- palavras que o hospedeiro compartilha com o programa.
\tconstant RAM_LAST_PAGE       : std_logic_vector(19 downto 0) :=
\t\tx"{last_page}";
{ram_external}\t-- Base da janela externa, em KiB; dali em diante é externo.
\tconstant EXT_BASE_KIB        : natural  := {ext_base};
\t-- Base da janela de periféricos, em KiB: os 2 GiB superiores do espaço.
\tconstant PERIPH_BASE_KIB     : natural  := {periph_base};
{memory}{peripherals}
end package {package};
"""


def _kib(value: int, what: str) -> int:
    """Convert an address to KiB, which the core's generics use.

    Parameters
    ----------
    value : int
        The address in bytes.
    what : str
        What the address is, for the error message.

    Returns
    -------
    int
        The address in KiB.

    Raises
    ------
    ValueError
        If the address is not a whole number of KiB.
    """
    if value % KIB:
        raise ValueError(f"{what} (0x{value:X}) is not a multiple of 1 KiB")
    return value // KIB


def _power_of_two(value: int) -> int:
    """Round a size up to the next power of two.

    Parameters
    ----------
    value : int
        The size in bytes.

    Returns
    -------
    int
        The smallest power of two that is at least `value`.
    """
    return 1 << (value - 1).bit_length()


def _hex(value: int) -> str:
    """Format a number for a linker flag.

    Parameters
    ----------
    value : int
        The number.

    Returns
    -------
    str
        `0x...`.
    """
    return f"0x{value:X}"


def render_specs(
    spec: dict[str, Any], table: dict[str, int], source: str
) -> str:
    """Render the GCC specs file with the linker flags of the map.

    Parameters
    ----------
    spec : dict of {str: Any}
        The `generate.specs` section: the `rom` and `ram` regions and
        the optional `ram_limit`, a reserved range that ends the RAM the
        linker may use.
    table : dict of {str: int}
        The symbols of the map.
    source : str
        The platform file, for the header.

    Returns
    -------
    str
        The file.
    """
    ram_base = table[f"{spec['ram']}.base"]
    limit = spec.get("ram_limit")
    ram_top = table[f"{limit}.base"] if limit else table[f"{spec['ram']}.end"]
    return _SPECS.format(
        source=source,
        rom_base=_hex(table[f"{spec['rom']}.base"]),
        rom_size=_hex(table[f"{spec['rom']}.size"]),
        ram_base=_hex(ram_base),
        ram_size=_hex(ram_top - ram_base),
        wait_restart=_hex(table["boot.wait_restart"]),
    )


def render_boot_ld(
    platform: dict[str, Any], table: dict[str, int], source: str
) -> str:
    """Render the linker script of the boot ROM.

    Parameters
    ----------
    platform : dict of {str: Any}
        The loaded platform: the first region is the boot ROM.
    table : dict of {str: int}
        The symbols of the map.
    source : str
        The platform file, for the header.

    Returns
    -------
    str
        The file.
    """
    boot = platform_list(platform, "regions")[0]["name"]
    return _BOOT_LD.format(
        source=source,
        origin=_hex(table[f"{boot}.base"]),
        length=_hex(table[f"{boot}.size"]),
        wait_restart=_hex(table["boot.wait_restart"]),
    )


def render_runtime(
    platform: dict[str, Any],
    spec: dict[str, Any],
    table: dict[str, int],
    source: str,
) -> str:
    """Render the header with the addresses shared with the program.

    Parameters
    ----------
    platform : dict of {str: Any}
        The loaded platform, for its peripherals.
    spec : dict of {str: Any}
        The `generate.runtime` section: the `ram` region whose end is
        `RV32_RAM_END`.
    table : dict of {str: int}
        The symbols of the map.
    source : str
        The platform file, for the header.

    Returns
    -------
    str
        The file: `RV32_RAM_END`, and `RV32_TOHOST_ADDR`,
        `RV32_FROMHOST_ADDR` and `RV32_STDOUT_BASE` for each reserved
        range the map has, `RV32_BOOT_ENTRY` (where the boot ROM
        jumps) and `RV32_<NAME>_BASE` for each peripheral.
    """
    values = {"RV32_RAM_END": table[f"{spec['ram']}.end"]}
    for name, macro in (
        ("tohost", "RV32_TOHOST_ADDR"),
        ("fromhost", "RV32_FROMHOST_ADDR"),
        ("stdout", "RV32_STDOUT_BASE"),
    ):
        if f"{name}.base" in table:
            values[macro] = table[f"{name}.base"]
    if "boot.entry" in table:
        values["RV32_BOOT_ENTRY"] = table["boot.entry"]
    for periph in platform_list(platform, "peripherals"):
        name = str(periph["name"]).upper()
        values[f"RV32_{name}_BASE"] = evaluate(periph["base"])
    defines = "\n".join(
        f"#define {macro} RV32_ADDRESS(0x{value:08X})"
        for macro, value in values.items()
    )
    return _RUNTIME.format(source=source, defines=defines)


def _peripheral_lines(platform: dict[str, Any]) -> str:
    """Write the VHDL constants for the base of every peripheral.

    Parameters
    ----------
    platform : dict of {str: Any}
        The loaded platform.

    Returns
    -------
    str
        One commented constant per peripheral, each preceded by a blank
        line; empty without peripherals.
    """
    lines = ""
    for periph in platform_list(platform, "peripherals"):
        name = str(periph["name"]).upper()
        base = evaluate(periph["base"])
        lines += (
            f"\n\t-- Endereço base do periférico {periph['name']}.\n"
            f"\tconstant {name}_BASE : "
            f'std_logic_vector(31 downto 0) := x"{base:08X}";\n'
            f"\t-- Índice da janela de 256 MiB do periférico {periph['name']}"
            f" (bits 30:28 do endereço).\n"
            f"\tconstant {name}_ID   : natural := {int(periph['id'])};\n"
        )
    return lines


def _external_line(kind: str, value: bool | None) -> str:
    """Write the constant that says a memory is outside the core.

    Parameters
    ----------
    kind : str
        `ROM` or `RAM`.
    value : bool or None
        Whether the memory is external; None when the platform leaves
        the choice to each model.

    Returns
    -------
    str
        The commented constant, or an empty string for None.
    """
    if value is None:
        return ""
    return (
        f"\t-- A {kind} fica fora do núcleo.\n"
        f"\tconstant {kind}_EXTERNAL        : boolean  := "
        f"{str(value).lower()};\n"
    )


def _externals(
    spec: dict[str, Any], memory: memory_choice.Memory | None
) -> tuple[bool | None, bool | None]:
    """Find whether the ROM and the RAM are external.

    Parameters
    ----------
    spec : dict of {str: Any}
        The `generate.vhdl` section, which may fix `rom_external` and
        `ram_external` when the platform has no `memory`.
    memory : Memory or None
        The memory choice, which takes over when there is one.

    Returns
    -------
    tuple of (bool or None, bool or None)
        The ROM and the RAM; None where nothing fixes the choice.
    """
    if memory is not None:
        return memory.rom_external, memory.ram_external
    rom = spec.get("rom_external")
    ram = spec.get("ram_external")
    return (
        None if rom is None else bool(rom),
        None if ram is None else bool(ram),
    )


def _profile_lines(platform: dict[str, Any], platform_file: Path) -> str:
    """Write the VHDL constants of the platform profile.

    Parameters
    ----------
    platform : dict of {str: Any}
        The loaded platform.
    platform_file : Path
        The platform YAML, which locates the profile specification.

    Returns
    -------
    str
        `HAS_E` (true for the RV32E) and, when the platform names the
        profile specification, one `HAS_*` switch per extension of the
        core.
    """
    base, generics = resolve(platform, platform_file)
    lines = (
        "\t-- O perfil é o RV32E (16 registradores); falso é o RV32I (32).\n"
        f"\tconstant HAS_E               : boolean  := "
        f"{str(base == 'e').lower()};\n"
    )
    for key in SWITCHES:
        if key in generics:
            lines += (
                f"\t-- A extensão {key[4:].capitalize()} está no perfil.\n"
                f"\tconstant {key.upper():<19} : boolean  := "
                f"{str(bool(generics[key])).lower()};\n"
            )
    return lines


def render_vhdl(
    platform: dict[str, Any],
    spec: dict[str, Any],
    table: dict[str, int],
    source: str,
    platform_file: Path,
) -> str:
    """Render the VHDL package with the generics of the core.

    Parameters
    ----------
    platform : dict of {str: Any}
        The loaded platform.
    spec : dict of {str: Any}
        The `generate.vhdl` section: `package`, the `rom` and `ram`
        regions, the optional `ext_base` and `periph_base` (both default
        to the peripheral window, `0x80000000`) and, when the platform
        fixes them and has no `memory`, `rom_external` and
        `ram_external`.
    table : dict of {str: int}
        The symbols of the map.
    source : str
        The platform file, for the header.
    platform_file : Path
        The platform YAML, which locates the profile specification.

    Returns
    -------
    str
        The file.
    """
    boot = platform_list(platform, "regions")[0]["name"]
    rom, ram = spec["rom"], spec["ram"]
    window = evaluate(spec.get("periph_base", PERIPHERAL_WINDOW_BASE))
    choice = memory_choice.resolve(platform)
    rom_external, ram_external = _externals(spec, choice)
    return _VHDL.format(
        source=source,
        package=spec["package"],
        profile=_profile_lines(platform, platform_file),
        boot_bits=(table[f"{boot}.size"] - 1).bit_length(),
        boot_bytes=table[f"{boot}.size"],
        rom_base=_kib(table[f"{rom}.base"], f"{rom} base"),
        rom_end=_kib(table[f"{rom}.end"], f"{rom} end"),
        rom_storage=_power_of_two(table[f"{rom}.end"]),
        rom_external=_external_line("ROM", rom_external),
        ram_base=_kib(table[f"{ram}.base"], f"{ram} base"),
        ram_end=_kib(table[f"{ram}.end"], f"{ram} end"),
        ram_storage=_power_of_two(table[f"{ram}.size"]),
        last_page=f"{(table[f'{ram}.end'] - PAGE) >> 12:05X}",
        ram_external=_external_line("RAM", ram_external),
        ext_base=_kib(evaluate(spec.get("ext_base", window)), "ext_base"),
        periph_base=_kib(window, "periph_base"),
        memory="" if choice is None else memory_choice.vhdl_lines(choice),
        peripherals=_peripheral_lines(platform),
    )


def render_all(platform_file: Path, root: Path) -> dict[Path, str]:
    """Render every file the platform asks to generate.

    Parameters
    ----------
    platform_file : Path
        The platform YAML.
    root : Path
        The project root the paths in `generate` are relative to.

    Returns
    -------
    dict of {Path: str}
        The absolute path of each file and its content.

    Raises
    ------
    ValueError
        If the map is inconsistent or an address is not a whole KiB.
    """
    platform = load_platform(platform_file)
    generics = None
    if memory_choice.declared(platform):
        _, generics = resolve(platform, platform_file)
    problems = validate_platform(platform, generics)
    if problems:
        raise ValueError("; ".join(str(p) for p in problems))
    table = symbols(platform)
    try:
        source = str(platform_file.relative_to(root))
    except ValueError:
        source = platform_file.name
    wanted = platform_dict(platform, "generate")
    out: dict[Path, str] = {}
    if "specs" in wanted:
        spec = cast(dict[str, Any], wanted["specs"])
        out[root / spec["path"]] = render_specs(spec, table, source)
    if "boot_ld" in wanted:
        spec = cast(dict[str, Any], wanted["boot_ld"])
        out[root / spec["path"]] = render_boot_ld(platform, table, source)
    if "runtime" in wanted:
        spec = cast(dict[str, Any], wanted["runtime"])
        out[root / spec["path"]] = render_runtime(
            platform, spec, table, source
        )
    if "vhdl" in wanted:
        spec = cast(dict[str, Any], wanted["vhdl"])
        out[root / spec["path"]] = render_vhdl(
            platform, spec, table, source, platform_file
        )
    return out


def write_all(platform_file: Path, root: Path) -> list[Path]:
    """Write the generated files.

    Parameters
    ----------
    platform_file : Path
        The platform YAML.
    root : Path
        The project root.

    Returns
    -------
    list of Path
        The files written.
    """
    files = render_all(platform_file, root)
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return list(files)


def check_all(platform_file: Path, root: Path) -> tuple[int, list[Mismatch]]:
    """Compare the generated files with what is on disk.

    Parameters
    ----------
    platform_file : Path
        The platform YAML.
    root : Path
        The project root.

    Returns
    -------
    tuple of (int, list of Mismatch)
        How many files were checked and the ones that are missing or
        out of date.
    """
    files = render_all(platform_file, root)
    problems = [
        Mismatch(
            "generate-memory-map",
            str(path.relative_to(root)),
            "missing" if not path.exists() else "out of date",
        )
        for path, text in files.items()
        if not path.exists() or path.read_text() != text
    ]
    return len(files), problems
