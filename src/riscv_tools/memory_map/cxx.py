"""Write what a platform needs to run C++ programs.

Under `generate`, `specs: {cxx: true}` makes the specs file link the
start and end objects of the GCC that register the unwind frames, and
`syscalls: {path: ...}` writes the C file with the system calls the
`libstdc++` asks of the runtime and picolibc does not provide.

```yaml
generate:
  specs:
    path: runtime/rv32im-fpga.specs
    rom: FLASH
    ram: RAM
    cxx: true
  syscalls:
    path: runtime/syscalls.c
```
"""

from typing import Any, cast

_START = "*startfile:\ncrt0-hosted%O%s\n"
_RENAME = "%rename link rv32imfpga_picolibc_link\n"
_LINK = "\n*link:\n"

# picolibc.ld has no place for the unwind tables the C++ link keeps,
# so the default linker script is picolibcpp.ld. A self_spec runs
# before the link spec, so the `%{!T*:}` test of picolibc.specs then
# sees a script and adds none; the spec the target had is renamed and
# kept.
_CXX_RENAME = _RENAME + "%rename self_spec rv32imfpga_self_spec\n"
_CXX_SELF = (
    "\n*self_spec:\n%(rv32imfpga_self_spec) %{!T:-T picolibcpp.ld}\n\n*link:\n"
)

_CXX_START = (
    "*startfile:\ncrt0-hosted%O%s crtbegin%O%s\n\n*endfile:\ncrtend%O%s\n"
)

_SYSCALLS = """\
/* Generated by `riscv-tools generate-memory-map` from {source}.
 * Do not edit by hand: change the platform YAML and run it again.
 *
 * The system calls the libstdc++ asks of the runtime and picolibc does
 * not provide: `std::random_device` (getentropy, read, open, close) is
 * linked into every program that uses `new` or an exception. The
 * platform has no operating system, so each fails with ENOSYS. */

#include <errno.h>
#include <stddef.h>
#include <sys/types.h>

int getentropy(void *buffer, size_t length)
{{
    (void)buffer;
    (void)length;
    errno = ENOSYS;
    return -1;
}}

ssize_t read(int fd, void *buffer, size_t length)
{{
    (void)fd;
    (void)buffer;
    (void)length;
    errno = ENOSYS;
    return -1;
}}

int open(const char *path, int flags, ...)
{{
    (void)path;
    (void)flags;
    errno = ENOSYS;
    return -1;
}}

int close(int fd)
{{
    (void)fd;
    errno = ENOSYS;
    return -1;
}}
"""


def wants_cxx(spec: dict[str, Any]) -> bool:
    """Tell whether a `specs` section asks for C++.

    Parameters
    ----------
    spec : dict of {str: Any}
        A `specs` or `bank_specs` entry.

    Returns
    -------
    bool
        The `cxx` key, False when absent.

    Raises
    ------
    ValueError
        `cxx` is not a boolean.
    """
    cxx = spec.get("cxx", False)
    if not isinstance(cxx, bool):
        raise ValueError(f"generate.specs.cxx must be true or false: {cxx!r}")
    return cxx


def cxx_specs(text: str) -> str:
    """Turn a rendered specs file into the one for C++.

    Parameters
    ----------
    text : str
        The specs file of a C program: it picks the `crt0` directly.

    Returns
    -------
    str
        The file with `crtbegin` after the `crt0`, a `*endfile` with
        `crtend`, and `picolibcpp.ld` as the default linker script.
        `picolibc.specs` leaves the objects out, so nothing would
        register the unwind frames and the end of `.eh_frame` would be
        garbage. It also drops the `--crt0=` switch of `picolibc.specs`,
        which is why the `crt0` is picked here.

    Raises
    ------
    ValueError
        The file lacks the `*startfile`, `%rename link` or `*link` the
        change hangs on.
    """
    for anchor in (_START, _RENAME, _LINK):
        if anchor not in text:
            raise ValueError(f"the specs file has no {anchor.strip()!r}")
    return (
        text.replace(_START, _CXX_START)
        .replace(_RENAME, _CXX_RENAME)
        .replace(_LINK, _CXX_SELF)
    )


def render_syscalls(wanted: dict[str, Any], source: str) -> str:
    """Render the C file with the system calls of the `libstdc++`.

    Parameters
    ----------
    wanted : dict of {str: Any}
        The `generate` section, which must ask for C++ in `specs` or in
        a `bank_specs` entry.
    source : str
        The platform file, for the header.

    Returns
    -------
    str
        `getentropy`, `read`, `open` and `close`, each failing with
        `ENOSYS`.

    Raises
    ------
    ValueError
        No specs file of the section has `cxx: true`: the stubs are for
        C++ only, and a C platform has no use for them.
    """
    entries = [
        cast(dict[str, Any], wanted.get("specs") or {}),
        *cast(list[dict[str, Any]], wanted.get("bank_specs") or []),
    ]
    if not any(wants_cxx(entry) for entry in entries):
        raise ValueError(
            "generate.syscalls is for C++: set cxx: true in generate.specs"
        )
    return _SYSCALLS.format(source=source)
