"""The FLASH banks of a platform and the files that carry them.

A platform that updates its program in the field splits the FLASH into
banks, each holding one image (see `riscv_tools.flash_image`):

```yaml
flash:
  region: FLASH
  banks:
    - {name: A, base: 0x1000,  size: 124K}
    - {name: B, base: 0x20000, size: 128K}
```

Each bank starts with the header page, so the program of a bank is
linked from `base + HEADER_SIZE`. The map gets, for the bank `A`, the
symbols `BANK_A.base|size|end|words` and `BANK_A_PAYLOAD.base|size|end|
words` (the part after the header page), which `generate.specs` takes as
its `rom` to link a program for that bank.
"""

from typing import Any, cast

from riscv_tools.flash_image import HEADER_SIZE, MAGIC, SECTOR_SIZE
from riscv_tools.memory_map.core import (
    Mismatch,
    platform_dict,
    platform_list,
)
from riscv_tools.memory_map.expressions import evaluate
from riscv_tools.memory_map.validation import overlaps, span

_HEADER = """\
/* Generated by `riscv-tools generate-memory-map` from {source}.
 * Do not edit by hand: change the platform YAML and run it again.
 *
 * The FLASH banks and the layout of the image each one holds: the
 * header page first, then the program. For the runtime in C and in
 * assembly (a .S file includes it too). */

#ifndef RV32_FLASH_BANKS_H
#define RV32_FLASH_BANKS_H

#ifndef RV32_ADDRESS
#ifdef __ASSEMBLER__
#define RV32_ADDRESS(value) value
#else
#define RV32_ADDRESS(value) value##u
#endif
#endif

#define RV32_IMAGE_MAGIC RV32_ADDRESS(0x{magic:08X})
#define RV32_IMAGE_HEADER_SIZE RV32_ADDRESS(0x{header:X})
{defines}
#endif
"""


def bank_list(platform: dict[str, Any]) -> list[dict[str, Any]]:
    """Read the banks of the platform.

    Parameters
    ----------
    platform : dict of {str: Any}
        The loaded platform.

    Returns
    -------
    list of dict of {str: Any}
        The `flash.banks` section; empty when the platform has none.
    """
    return platform_list(platform_dict(platform, "flash"), "banks")


def symbols(platform: dict[str, Any]) -> dict[str, int]:
    """Name the banks and their payloads for the checks and the specs.

    Parameters
    ----------
    platform : dict of {str: Any}
        The loaded platform.

    Returns
    -------
    dict of {str: int}
        `BANK_<name>` and `BANK_<name>_PAYLOAD`, each with `base`,
        `size`, `end` and `words`.
    """
    out: dict[str, int] = {}
    for bank in bank_list(platform):
        base = evaluate(bank["base"])
        size = evaluate(bank["size"])
        for name, start, length in (
            (f"BANK_{bank['name']}", base, size),
            (
                f"BANK_{bank['name']}_PAYLOAD",
                base + HEADER_SIZE,
                size - HEADER_SIZE,
            ),
        ):
            out |= {
                f"{name}.base": start,
                f"{name}.size": length,
                f"{name}.end": start + length,
                f"{name}.words": length // 4,
            }
    return out


def _bank_problems(
    bank: dict[str, Any], rom: tuple[int, int] | None
) -> list[Mismatch]:
    """Check one bank against the sector and the ROM region.

    Parameters
    ----------
    bank : dict of {str: Any}
        The bank.
    rom : tuple of (int, int) or None
        Base and size of the FLASH region, or None if it is missing.

    Returns
    -------
    list of Mismatch
        The problems of the bank.
    """
    name = f"flash bank {bank['name']}"
    base, size = evaluate(bank["base"]), evaluate(bank["size"])
    problems: list[Mismatch] = []
    if base % SECTOR_SIZE or size % SECTOR_SIZE:
        problems.append(
            Mismatch(
                "platform",
                "",
                f"{name} ({span(base, size)}) is not aligned to the "
                f"{SECTOR_SIZE}-byte sector",
            )
        )
    if size <= HEADER_SIZE:
        problems.append(
            Mismatch("platform", "", f"{name} has no room for a program")
        )
    if rom is not None and not rom[0] <= base <= base + size <= sum(rom):
        problems.append(
            Mismatch(
                "platform",
                "",
                f"{name} ({span(base, size)}) is not inside the FLASH",
            )
        )
    return problems


def problems(platform: dict[str, Any]) -> list[Mismatch]:
    """Check that the banks are well formed and fit the FLASH.

    Parameters
    ----------
    platform : dict of {str: Any}
        The loaded platform.

    Returns
    -------
    list of Mismatch
        Missing region, banks that are not sector aligned, have no room
        for a program, fall outside the FLASH region, overlap, or share
        a name; empty when the platform has no banks.
    """
    banks = bank_list(platform)
    if not banks:
        return []
    flash = platform_dict(platform, "flash")
    region = next(
        (
            r
            for r in platform_list(platform, "regions")
            if r["name"] == flash.get("region")
        ),
        None,
    )
    rom = None
    out: list[Mismatch] = []
    if region is None:
        out.append(Mismatch("platform", "", "flash.region names no region"))
    else:
        rom = (evaluate(region["base"]), evaluate(region["size"]))
    names = [str(b["name"]) for b in banks]
    if len(set(names)) != len(names):
        out.append(Mismatch("platform", "", "flash banks share a name"))
    for bank in banks:
        out += _bank_problems(bank, rom)
    spans = [
        (str(b["name"]), evaluate(b["base"]), evaluate(b["size"]))
        for b in banks
    ]
    return out + overlaps("flash banks", spans)


def render_header(
    platform: dict[str, Any], table: dict[str, int], source: str
) -> str:
    """Render the header with the banks and the image layout.

    Parameters
    ----------
    platform : dict of {str: Any}
        The loaded platform.
    table : dict of {str: int}
        The symbols of the map, banks included.
    source : str
        The platform file, for the header.

    Returns
    -------
    str
        The file: `RV32_IMAGE_MAGIC`, `RV32_IMAGE_HEADER_SIZE` and, for
        each bank, `RV32_BANK_<name>_BASE`, `_SIZE` and `_ENTRY` (where
        its program starts, right after the header page).
    """
    lines: list[str] = []
    for bank in bank_list(platform):
        name = str(bank["name"]).upper()
        key = f"BANK_{bank['name']}"
        for suffix, value in (
            ("BASE", table[f"{key}.base"]),
            ("SIZE", table[f"{key}.size"]),
            ("ENTRY", table[f"{key}_PAYLOAD.base"]),
        ):
            lines.append(
                f"#define RV32_BANK_{name}_{suffix} "
                f"RV32_ADDRESS(0x{value:08X})"
            )
    return _HEADER.format(
        source=source,
        magic=MAGIC,
        header=HEADER_SIZE,
        defines="\n".join(lines),
    )


def header_path(wanted: dict[str, Any]) -> str | None:
    """Find where the banks header goes.

    Parameters
    ----------
    wanted : dict of {str: Any}
        The `generate` section.

    Returns
    -------
    str or None
        The `banks_h.path`, or None when the platform does not ask.
    """
    spec = wanted.get("banks_h")
    return None if spec is None else str(cast(dict[str, Any], spec)["path"])
