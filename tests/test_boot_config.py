PLATFORM: dict[str, Any] = {
    "profile": "rv32im_zicntr",
    "extras": ["Interrupts"],
    "boot": {"entry": "0x800", "wait_restart": "0x100"},
    "reserved": MAP_RESERVED,
    "regions": MAP_REGIONS,
    "generate": {
        "boot_config_h": {"path": "out/boot_config.h"},
        "boot_ld": {"path": "out/boot.ld"},
        "specs": {
            "ram_limit": "stdout",
            "ram": "RAM",
            "rom": "FLASH",
            "path": "out/x.specs",
        },
    },
    "peripherals": [{"name": "UART", "base": "0xC0000000", "size": "16"}],
}
MEMORY: dict[str, Any] = {
    "rom": {"external": True},
    "ram": {"external": True},
    "icache": {"enabled": True, "size_bits": 4096},
    "dcache": {"enabled": False},
}
HEADER = "out/boot_config.h"
SPECS = "out/x.specs"
# Palavras de uma linha `#define NOME valor`.
DEFINE_WORDS = 3


@pytest.fixture(autouse=True)
def _no_override() -> None:
    """Start each test without `--profile`."""
    set_override(None)


def _platform(**changes: Any) -> dict[str, Any]:
    """Copy the platform and replace top-level sections."""
    merged = deepcopy(PLATFORM) | changes
    return {key: value for key, value in merged.items() if value is not None}


def _write(root: Path, platform: dict[str, Any]) -> Path:
    """Write the platform as the file the Tools read."""
    target = root.joinpath("platform.yaml")
    target.write_text(dump_platform(platform))
    return target


def _render(root: Path, platform: dict[str, Any]) -> dict[str, str]:
    """Render the files of a platform, by the path under `root`."""
    files = render_all(_write(root, platform), root)
    return {str(path.relative_to(root)): text for path, text in files.items()}


def _macros(text: str) -> dict[str, int]:
    """Read the `#define NAME value` lines of the header."""
    found: dict[str, int] = {}
    for line in text.splitlines():
        words = line.split()
        if line.startswith("#define RV32_") and len(words) == DEFINE_WORDS:
            _, name, value = words
            found[name] = int(value)
    return found


def _problem(root: Path, platform: dict[str, Any]) -> str:
    """Render a platform that must be refused and return the reason."""
    with pytest.raises(ValueError) as caught:
        render_all(_write(root, platform), root)
    return str(caught.value)


def test_boot_config_has_one_macro_per_extension(tmp_path: Path) -> None:
    """Each extension and extra of the core is a 0 or 1 macro."""
    text = _render(tmp_path, _platform())[HEADER]
    macros = _macros(text)
    check_equal(
        macros,
        {
            "RV32_HAS_M": 1,
            "RV32_HAS_ZMMUL": 0,
            "RV32_HAS_ZICSR": 1,
            "RV32_HAS_ZICNTR": 1,
            "RV32_HAS_ZIHPM": 0,
            "RV32_HAS_ZIFENCEI": 0,
            "RV32_HAS_ZICCLSM": 0,
            "RV32_HAS_ZIMOP": 0,
            "RV32_HAS_ZICOND": 0,
            "RV32_HAS_ZIHINTNTL": 0,
            "RV32_HAS_ZIHINTPAUSE": 0,
            "RV32_HAS_INTERRUPTS": 1,
            "RV32_HAS_SSCOFPMF": 0,
            "RV32_HAS_ACCESS_FAULTS": 0,
            "RV32_IS_E": 0,
            "RV32_TEST_WAIT": 1,
        },
    )
    check(text.startswith("/* Generated by `riscv-tools"))
    check_in("#ifndef RV32_BOOT_CONFIG_H", text)


def test_boot_config_follows_the_profile_and_the_extras(
    tmp_path: Path,
) -> None:
    """A base E core with other extensions flips the matching macros."""
    platform = _platform(
        profile="rv32e_zmmul_zifencei_zimop",
        extras=["Zihintpause", "AccessFaults", "Sscofpmf"],
    )
    macros = _macros(_render(tmp_path, platform)[HEADER])
    on = {name for name, value in macros.items() if value}
    check_equal(
        on,
        {
            "RV32_HAS_ZMMUL",
            "RV32_HAS_ZIFENCEI",
            "RV32_HAS_ZIMOP",
            "RV32_HAS_ZIHINTPAUSE",
            "RV32_HAS_ACCESS_FAULTS",
            "RV32_HAS_SSCOFPMF",
            "RV32_IS_E",
            "RV32_TEST_WAIT",
        },
    )


def test_zihpm_turns_zicsr_on(tmp_path: Path) -> None:
    """Zihpm implies Zicsr, as Zicntr does."""
    macros = _macros(
        _render(tmp_path, _platform(profile="rv32i_zihpm", extras=[]))[HEADER]
    )
    check_equal(macros["RV32_HAS_ZICSR"], 1)
    check_equal(macros["RV32_HAS_ZIHPM"], 1)
    check_equal(macros["RV32_HAS_ZICNTR"], 0)


def test_test_wait_follows_boot_wait_restart(tmp_path: Path) -> None:
    """Without `boot.wait_restart` the boot memory is an application."""
    boot = {"entry": "0x800"}
    files = _render(tmp_path, _platform(boot=boot))
    check_equal(_macros(files[HEADER])["RV32_TEST_WAIT"], 0)
    check_not_in("rv32_wait_restart", files[SPECS])
    check_not_in("RESET_RESERVED", files["out/boot.ld"])
    check_not_in("wait_restart", files["out/boot.ld"])
    check_in("ORIGIN = 0x0, LENGTH = 0x800", files["out/boot.ld"])
    check_in(".text.reset 0x0", files["out/boot.ld"])
    tests = _render(tmp_path, _platform())
    check_equal(_macros(tests[HEADER])["RV32_TEST_WAIT"], 1)
    check_in("rv32_wait_restart=0x100", tests[SPECS])


def test_the_header_is_checked_like_the_other_files(tmp_path: Path) -> None:
    """`check_all` reports a missing or stale header."""
    platform = _write(tmp_path, _platform())
    count, problems = check_all(platform, tmp_path)
    check_equal(count, 3)
    check(any(HEADER in str(p) for p in problems))
    for path, text in render_all(platform, tmp_path).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    check_equal(check_all(platform, tmp_path)[1], [])
    (tmp_path / HEADER).write_text("#define RV32_IS_E 1\n")
    check_equal(len(check_all(platform, tmp_path)[1]), 1)


@pytest.mark.skipif(shutil.which(GCC) is None, reason=f"needs {GCC} on PATH")
def test_an_assembly_file_can_include_the_header(tmp_path: Path) -> None:
    """The preprocessor of a `.S` file reads the macros."""
    header = tmp_path / "boot_config.h"
    header.write_text(_render(tmp_path, _platform())[HEADER])
    source = tmp_path / "boot.S"
    source.write_text(
        '#include "boot_config.h"\n'
        "#if RV32_HAS_ZICSR && !RV32_HAS_ZIFENCEI && RV32_TEST_WAIT\n"
        "    nop\n"
        "#else\n"
        "    #error wrong switches\n"
        "#endif\n"
    )
    done = subprocess.run(
        [GCC, "-E", "-x", "assembler-with-cpp", str(source)],
        check=False,
        capture_output=True,
        text=True,
    )
    check_equal(done.returncode, 0, done.stderr)
    check_in("nop", done.stdout)


def test_specs_without_march_are_unchanged(tmp_path: Path) -> None:
    """A `specs` section without `march` writes what it always wrote."""
    text = _render(tmp_path, _platform())[SPECS]
    check_not_in("self_spec", text)
    check_in(
        "--defsym=__ram=0x8000 --defsym=__ram_size=0x27BE0 "
        "%{!DRV32_SPIKE:--defsym=rv32_wait_restart=0x100}\n",
        text,
    )
    check(text.endswith("*startfile:\ncrt0-hosted%O%s\n"))


def _with_march(**changes: Any) -> dict[str, Any]:
    """Copy the platform with `march` on in the specs section."""
    platform = _platform()
    platform["generate"]["specs"] |= {"march": True} | changes
    return platform


def test_specs_with_march_carry_the_march_and_the_abi(tmp_path: Path) -> None:
    """The self spec swaps the toolchain default for the core's pair."""
    text = _render(tmp_path, _with_march())[SPECS]
    tail = (
        "*startfile:\ncrt0-hosted%O%s\n\n*self_spec:\n"
        "%{march=rv32im_zmmul:%<march=* %<mabi=*"
        " -march=rv32im_zicsr_zicntr -mabi=ilp32}\n"
    )
    check(text.endswith(tail), text)


def test_specs_march_follows_the_profile_and_the_default(
    tmp_path: Path,
) -> None:
    """A base E core gets `ilp32e`, and the default can be changed."""
    platform = _with_march(default_march="rv32i")
    platform |= {"profile": "rv32em_zicsr", "extras": ["Zihintpause"]}
    text = _render(tmp_path, platform)[SPECS]
    check_in(
        "%{march=rv32i:%<march=* %<mabi=*"
        " -march=rv32em_zicsr_zihintpause -mabi=ilp32e}",
        text,
    )


def test_the_profile_override_changes_the_march(tmp_path: Path) -> None:
    """`--profile` replaces the profile the `-march` comes from."""
    path = _write(tmp_path, _with_march())
    set_override("rv32e")
    try:
        text = render_all(path, tmp_path)[tmp_path / SPECS]
    finally:
        set_override(None)
    check_in("-march=rv32e -mabi=ilp32e}", text)


def test_the_core_of_the_platform_gives_the_march(tmp_path: Path) -> None:
    """`platform_core` rebuilds the block of the platform."""
    platform = load_platform(_write(tmp_path, _platform()))
    core = platform_core(platform)
    check_equal(core["extensions"], ["M", "Zicntr", "Interrupts"])
    check_equal(march_of(core), "rv32im_zicsr_zicntr")


@pytest.mark.skipif(shutil.which(GCC) is None, reason=f"needs {GCC} on PATH")
@pytest.mark.parametrize(
    ("profile", "extras", "multilib"),
    [
        ("rv32i_zicsr", [], "rv32i/ilp32"),
        ("rv32e_zmmul", ["Zihintpause"], "rv32e_zmmul/ilp32e"),
        ("rv32em", [], "rv32em_zmmul/ilp32e"),
        ("rv32im_zicntr", ["Interrupts"], "."),
    ],
)
def test_gcc_uses_the_core_when_the_program_has_no_march(
    tmp_path: Path, profile: str, extras: list[str], multilib: str
) -> None:
    """A program without `-march` gets the core's and keeps its own."""
    platform = _with_march(default_march=_gcc_default())
    platform |= {"profile": profile, "extras": extras}
    specs = tmp_path / "x.specs"
    specs.write_text(_render(tmp_path, platform)[SPECS])
    core = platform_core(load_platform(_write(tmp_path, platform)))
    base = [GCC, f"--specs={specs}"]
    check_equal(_run([*base, "-print-multi-directory"]), multilib)
    plan = _run([*base, "-###", "-c", "/dev/null", "-x", "c"], "stderr")
    check_in(f"-march={march_of(core)}", plan)
    own = _run(
        [
            *base,
            "-march=rv32e_zicsr",
            "-mabi=ilp32e",
            "-###",
            "-x",
            "c",
            "-c",
            "/dev/null",
        ],
        "stderr",
    )
    check_in("-march=rv32e_zicsr", own)
    check_not_in(f"-march={march_of(core)} ", own)


def _gcc_default() -> str:
    """Read the `-march` the compiler assumes without one."""
    plan = _run([GCC, "-###", "-x", "c", "-c", "/dev/null"], "stderr")
    return plan.split("-march=", 1)[1].split()[0].strip("'\"")


def _run(command: list[str], stream: str = "stdout") -> str:
    """Run a command and return one of its streams."""
    done = subprocess.run(command, check=False, capture_output=True, text=True)
    check_equal(done.returncode, 0, done.stderr)
    return (done.stderr if stream == "stderr" else done.stdout).strip()


def test_a_64_bit_core_is_refused(tmp_path: Path) -> None:
    """V-I1: the image has no RV64 multilib."""
    reason = _problem(tmp_path, _platform(profile="rv64i", extras=[]))
    check_in("V-I1", reason)
    check_in("use core.type 32", reason)


def test_a_64_bit_core_is_refused_by_the_check(tmp_path: Path) -> None:
    """`check-memory-map` reports the same problem as the generation."""
    platform = _write(tmp_path, _platform(profile="rv64im", extras=[]))
    with pytest.raises(ValueError, match="V-I1"):
        check_all(platform, tmp_path)


def test_the_extension_q_is_refused(tmp_path: Path) -> None:
    """The GCC 16.1.0 does not support Q, and the message says so."""
    data = yaml.safe_load(dump_platform(_platform()))
    data["core"]["extensions"].append("Q")
    path = tmp_path / "platform.yaml"
    path.write_text(yaml.safe_dump(data))
    with pytest.raises(ValueError, match="Q is refused") as caught:
        load_platform(path)
    check_in("GCC 16.1.0", str(caught.value))
    check_in("remove Q", str(caught.value))


@pytest.mark.parametrize(
    ("memory", "caches"),
    [
        (MEMORY, "icache"),
        (
            {
                **MEMORY,
                "icache": {"enabled": False},
                "dcache": {"enabled": True, "size_bits": 1024},
            },
            "dcache",
        ),
        (
            {**MEMORY, "dcache": {"enabled": True, "size_bits": 1024}},
            "icache and dcache",
        ),
    ],
)
def test_a_cache_needs_zifencei(
    tmp_path: Path, memory: dict[str, Any], caches: str
) -> None:
    """V-I2: `fence.i` is what makes the caches drop their lines."""
    platform = _platform(
        profile="rv32i",
        extras=[],
        memory=memory,
        config={"rom": "FLASH", "ram": "RAM"},
    )
    reason = _problem(tmp_path, platform)
    check_in(
        f"V-I2 the platform has {caches} but the core lacks Zifencei", reason
    )
    check_in("add Zifencei to core.extensions", reason)
    platform["profile"] = "rv32i_zifencei"
    check_in("out/x.specs", _render(tmp_path, platform))


def test_no_cache_needs_no_zifencei(tmp_path: Path) -> None:
    """Without a cache the core may lack Zifencei."""
    memory = {**MEMORY, "icache": {"enabled": False}}
    platform = _platform(profile="rv32i", extras=[], memory=memory)
    check_in(SPECS, _render(tmp_path, platform))


def _with_boot(size: str, wait: str | None = "0x100") -> dict[str, Any]:
    """Copy the platform with a BOOT_MEMORY of the given size."""
    boot = {"entry": "0x800"} | ({"wait_restart": wait} if wait else {})
    regions = [{**MAP_REGIONS[0], "size": size}, *MAP_REGIONS[1:]]
    platform = _platform(boot=boot, regions=regions)
    platform["generate"].pop("boot_ld")
    return platform


def test_the_boot_memory_size_must_be_a_power_of_two(tmp_path: Path) -> None:
    """V-B1: 3K is refused and says what to write."""
    reason = _problem(tmp_path, _with_boot("3K"))
    check_in("V-B1 BOOT_MEMORY size 3072 bytes is not a power of two", reason)
    check_in("2K, 4K, 8K", reason)
    check_in(SPECS, _render(tmp_path, _with_boot("2K")))


def test_the_wait_loop_needs_room_in_the_boot_memory(tmp_path: Path) -> None:
    """V-B2: `wait_restart` too close to the end leaves no room."""
    reason = _problem(tmp_path, _with_boot("2K", "0x7F0"))
    check_in("V-B2 BOOT_MEMORY (2048 bytes) ends 16 bytes after", reason)
    check_in("boot.wait_restart 0x7F0", reason)
    check_in("needs 20", reason)
    check_in(SPECS, _render(tmp_path, _with_boot("2K", "0x7E0")))
    check_in(SPECS, _render(tmp_path, _with_boot("2K", None)))


def test_check_memory_map_reports_the_refusals(tmp_path: Path) -> None:
    """`check-memory-map` returns the problems of the generation."""
    path = _write(tmp_path, _platform(profile="rv64im", extras=[]))
    _, problems = check_memory_map(path, tmp_path)
    check(any("V-I1" in str(p) for p in problems), str(problems))

    path = _write(tmp_path, _with_boot("1536"))
    _, problems = check_memory_map(path, tmp_path)
    check(any("V-B1" in str(p) for p in problems), str(problems))
