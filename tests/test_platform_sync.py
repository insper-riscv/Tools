"""Tests for platform_sync."""

import argparse
from pathlib import Path
from typing import Any

import pytest
import yaml
from support import check, check_equal, check_false, check_in, check_not_in

from riscv_tools import cli
from riscv_tools.cli.platform_cmd import cmd_platform
from riscv_tools.platform_sync import (
    PATH_KEYS,
    check_output,
    flatten,
    rebase,
    render,
    write_output,
)

BASE = """\
toolchain:
  specs: src/sim/runtime/rv32im-fpga.specs
paths:
  boot_memory: src/sim/runtime/boot_memory.S
  sources: [src/sim/runtime/_exit.c, src/sim/runtime/stdio.c]
  include_dir: include
quartus:
  project_dir: src/sim/quartus
  project_name: core_fpga_test
sim:
  vhdl_sources: [Core/src/core.vhd, Memory/sim/ram.vhd]
  python_path: [src/sim]
emulator:
  sources: [src/sim/runtime/spike_exit.S]
"""
BOARD = """\
extends: ../sim/config.yaml
quartus:
  project_dir: src/board
  project_name: de0-cv
sim:
  vhdl_sources: [Core/src/core.vhd, src/board/top.vhd]
"""


def _platform(root: Path) -> Path:
    """Write a two-level platform config and return the derived one."""
    (root / "src/sim").mkdir(parents=True)
    (root / "src/board").mkdir(parents=True)
    (root / "src/sim/config.yaml").write_text(BASE)
    (root / "src/board/config.yaml").write_text(BOARD)
    return root / "src/board/config.yaml"


def _args(root: Path, **overrides: object) -> argparse.Namespace:
    """Build the arguments of the platform command."""
    values: dict[str, object] = {
        "action": "sync",
        "source": "src/board/config.yaml",
        "prefix": "Insper-RISC-V",
        "output": "out/config.de0-cv.yaml",
        "check": False,
        "root": str(root),
        "config": None,
    }
    values.update(overrides)
    return argparse.Namespace(**values)


def test_flatten_resolves_the_extends_chain(tmp_path: Path) -> None:
    """The derived config is merged over its base."""
    config = flatten(_platform(tmp_path))
    check_not_in("extends", config)
    check_equal(
        config["toolchain"]["specs"], "src/sim/runtime/rv32im-fpga.specs"
    )
    check_equal(config["quartus"]["project_dir"], "src/board")
    check_equal(config["sim"]["vhdl_sources"][1], "src/board/top.vhd")


def test_rebase_prefixes_every_path_the_platform_owns(tmp_path: Path) -> None:
    """Strings and lists of paths get the submodule folder."""
    config = rebase(flatten(_platform(tmp_path)), "Insper-RISC-V")
    check_equal(
        config["toolchain"]["specs"],
        "Insper-RISC-V/src/sim/runtime/rv32im-fpga.specs",
    )
    check_equal(
        config["paths"]["sources"],
        [
            "Insper-RISC-V/src/sim/runtime/_exit.c",
            "Insper-RISC-V/src/sim/runtime/stdio.c",
        ],
    )
    check_equal(config["sim"]["python_path"], ["Insper-RISC-V/src/sim"])
    check_equal(config["quartus"]["project_dir"], "Insper-RISC-V/src/board")


def test_rebase_leaves_the_consumers_paths_and_other_keys(
    tmp_path: Path,
) -> None:
    """include_dir belongs to the consumer, and names stay."""
    config = rebase(flatten(_platform(tmp_path)), "Insper-RISC-V")
    check_equal(config["paths"]["include_dir"], "include")
    check_equal(config["quartus"]["project_name"], "de0-cv")


def test_rebase_keeps_an_absolute_path_and_does_not_mutate() -> None:
    """An absolute path keeps its form and the input is intact."""
    original: dict[str, Any] = {
        "toolchain": {"specs": "/opt/x.specs"},
        "memory": {"ram": 4},
    }
    result = rebase(original, "Sub")
    check_equal(result["toolchain"]["specs"], "/opt/x.specs")
    original["toolchain"]["specs"] = "changed"
    check_equal(result["toolchain"]["specs"], "/opt/x.specs")


def test_rebase_skips_a_missing_section() -> None:
    """A config without a listed section is not an error."""
    check_equal(
        rebase({"memory": {"ram_base": 4}}, "Sub"), {"memory": {"ram_base": 4}}
    )
    check_in(("sim", "vhdl_sources"), PATH_KEYS)


def test_render_starts_with_the_header_and_loads_back(tmp_path: Path) -> None:
    """The text says it is generated and is valid YAML."""
    config = rebase(flatten(_platform(tmp_path)), "Insper-RISC-V")
    text = render(config, "src/board/config.yaml", "Insper-RISC-V")
    check(text.startswith("# Generated by `riscv-tools platform sync`"))
    check_equal(yaml.safe_load(text), config)
    check(text.endswith("\n"))


def test_check_output_reports_missing_and_different(tmp_path: Path) -> None:
    """A missing file and a stale one are both problems."""
    target = tmp_path / "config.yaml"
    check_in("missing", check_output(target, "a\n")[0])
    write_output(target, "a\n")
    check_false(check_output(target, "a\n"))
    check_in("differs", check_output(target, "b\n")[0])


def test_write_output_creates_the_folders(tmp_path: Path) -> None:
    """The output folder does not have to exist."""
    target = tmp_path / "a" / "b" / "config.yaml"
    write_output(target, "x\n")
    check_equal(target.read_text(), "x\n")


def test_sync_then_check_passes_and_a_change_fails(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """The written file passes --check until the platform changes."""
    _platform(tmp_path)
    cmd_platform(_args(tmp_path))
    cmd_platform(_args(tmp_path, check=True))
    check_in("platform OK", capsys.readouterr().out)
    (tmp_path / "src/board/config.yaml").write_text(
        BOARD.replace("de0-cv", "other")
    )
    with pytest.raises(SystemExit) as stop:
        cmd_platform(_args(tmp_path, check=True))
    check_equal(stop.value.code, 1)
    check_in("differs", capsys.readouterr().err)


def test_command_runs_through_the_cli_without_config(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    """`riscv-tools platform sync` runs without `--config`."""
    _platform(tmp_path)
    argv = ["riscv-tools"]
    argv += ["--root", str(tmp_path)]
    argv += ["platform", "sync"]
    argv += ["--source", "src/board/config.yaml"]
    argv += ["--prefix", "Insper-RISC-V"]
    argv += ["--output", "out/config.de0-cv.yaml"]
    monkeypatch.setattr("sys.argv", argv)
    cli.main()
    check_in("platform synced", capsys.readouterr().out)
    written = yaml.safe_load((tmp_path / "out/config.de0-cv.yaml").read_text())
    check_equal(written["quartus"]["project_dir"], "Insper-RISC-V/src/board")
