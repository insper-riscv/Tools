"""Tests for the files generated from the memory map."""

import argparse
import sys
from pathlib import Path
from typing import Any

import pytest
import yaml
from support import (
    MAP_REGIONS,
    MAP_RESERVED,
    check,
    check_equal,
    check_in,
    check_not_in,
    dump_platform,
)

from riscv_tools import cli
from riscv_tools.memory_map import (
    check_all,
    check_memory_map,
    render_all,
    set_override,
    write_all,
)

PLATFORM: dict[str, Any] = {
    "regions": MAP_REGIONS,
    "reserved": MAP_RESERVED,
    "boot": {"entry": "0x800", "wait_restart": "0x100"},
    "peripherals": [{"name": "UART", "base": "0xC0000000", "size": "16"}],
    "generate": {
        "specs": {
            "path": "out/x.specs",
            "rom": "FLASH",
            "ram": "RAM",
            "ram_limit": "stdout",
        },
        "boot_ld": {"path": "out/boot.ld"},
        "runtime": {"path": "out/memory_map.h", "ram": "RAM"},
        "vhdl": {
            "path": "out/map_pkg.vhd",
            "package": "map_pkg",
            "rom": "FLASH",
            "ram": "RAM",
        },
    },
}


def _write(root: Path, platform: dict[str, Any] | None = None) -> Path:
    path = root / "platform.yaml"
    path.write_text(dump_platform(platform or PLATFORM))
    return path


def test_specs_carries_the_linker_flags_of_the_map(tmp_path: Path) -> None:
    """The specs file has the base and size of the ROM and the RAM."""
    files = render_all(_write(tmp_path), tmp_path)
    text = files[tmp_path / "out/x.specs"]
    _has(
        text,
        "--defsym=__flash=0x800 --defsym=__flash_size=0x7800",
        "--defsym=__ram=0x8000 --defsym=__ram_size=0x27BE0",
        "rv32_wait_restart=0x100",
    )
    check(text.startswith("# Generated by `riscv-tools"))


def test_boot_linker_script_has_the_boot_region(tmp_path: Path) -> None:
    """The boot linker script has the boot region and the restart."""
    files = render_all(_write(tmp_path), tmp_path)
    text = files[tmp_path / "out/boot.ld"]
    _has(
        text,
        "ORIGIN = 0x0, LENGTH = 0x800",
        "RESET_RESERVED = 0x100;",
    )


def _profiled(profile: str, **changes: Any) -> dict[str, Any]:
    """Copy the platform with a profile of ``matrix.yaml``."""
    platform = yaml.safe_load(yaml.safe_dump(PLATFORM))
    platform |= {"profile": profile, "profiles": "matrix.yaml", **changes}
    set_override(None)
    return platform


def _has(text: str, *lines: str) -> None:
    """Check that every line is in the text."""
    for line in lines:
        check_in(line, text)


def _map_package(base: Path, platform: dict[str, Any] | None = None) -> str:
    """Render the files of a platform, return the generics package."""
    return render_all(_write(base, platform), base)[base / "out/map_pkg.vhd"]


def test_vhdl_package_has_the_generics_in_kib(tmp_path: Path) -> None:
    """The VHDL package has the core generics and the peripherals."""
    text = _map_package(tmp_path)
    _has(
        text,
        "constant IS_E                : boolean  := false;",
        "constant BOOT_MEMORY_BITS       : natural  := 11;",
        "constant BOOT_MEMORY_SIZE_BYTES : positive := 2048;",
        "constant FLASH_BASE_KIB      : natural  := 2;",
        "constant FLASH_END_KIB       : natural  := 32;",
        "constant FLASH_STORAGE_BYTES : positive := 32768;",
        "constant RAM_BASE_KIB        : natural  := 32;",
        "constant RAM_END_KIB         : natural  := 192;",
        "constant RAM_STORAGE_BYTES   : positive := 262144;",
        "constant RAM_LAST_PAGE       :",
        'x"0002F"',
        "constant PERIPH_COUNT : natural := 1;",
        "constant STRICT_PERIPH : boolean := true;",
        "constant UART_INDEX : natural := 0;",
        "constant UART_BASE : addr_t := "
        'std_logic_vector(resize(unsigned\'(x"C0000000"), ADDR_BITS));',
        "UART_INDEX => UART_BASE",
        'UART_INDEX => std_logic_vector(resize(unsigned\'(x"FFFFFFF0"), '
        "ADDR_BITS))",
    )
    check_not_in("EXTERNAL", text)
    check_not_in("ROM_", text)
    check_not_in("EXT_BASE", text)
    check_not_in("PERIPH_SLOTS", text)


def test_write_then_check_passes_and_a_change_is_caught(
    tmp_path: Path,
) -> None:
    """A written set checks clean, and an edited file is reported."""
    platform = _write(tmp_path)
    written = write_all(platform, tmp_path)
    check_equal(len(written), 4)
    count, problems = check_all(platform, tmp_path)
    check_equal(count, 4)
    check_equal(problems, [])
    (tmp_path / "out/boot.ld").write_text("hand edited\n")
    (tmp_path / "out/x.specs").unlink()
    _, problems = check_all(platform, tmp_path)
    details = sorted(p.detail for p in problems)
    check_equal(details, ["missing", "out of date"])


def test_an_address_that_is_not_a_whole_kib_is_rejected(
    tmp_path: Path,
) -> None:
    """The core's generics are in KiB, so a ragged end is an error."""
    bad = yaml.safe_load(yaml.safe_dump(PLATFORM))
    bad["regions"][1]["size"] = "0x7A0"
    with pytest.raises(ValueError, match="multiple of 1 KiB"):
        render_all(_write(tmp_path, bad), tmp_path)


def test_an_inconsistent_map_is_not_generated(tmp_path: Path) -> None:
    """Overlapping regions stop the generation."""
    bad = yaml.safe_load(yaml.safe_dump(PLATFORM))
    bad["regions"][2]["base"] = "0x1000"
    with pytest.raises(ValueError, match="overlap"):
        render_all(_write(tmp_path, bad), tmp_path)


def test_the_command_writes_and_checks(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """The subcommand writes the files and `--check` then passes."""
    _write(tmp_path)
    args = argparse.Namespace(
        platform="platform.yaml", check=False, root=str(tmp_path), config=None
    )
    cli.cmd_generate_memory_map(args)
    check_in("generated: out/x.specs", capsys.readouterr().out)
    args.check = True
    cli.cmd_generate_memory_map(args)
    check_in("generated files OK: 4", capsys.readouterr().out)
    (tmp_path / "out/map_pkg.vhd").write_text("old\n")
    with pytest.raises(SystemExit) as stop:
        cli.cmd_generate_memory_map(args)
    check_equal(stop.value.code, 1)


def test_the_external_flags_appear_when_the_platform_fixes_them(
    tmp_path: Path,
) -> None:
    """`rom_external` and `ram_external` become constants when given."""
    fixed = yaml.safe_load(yaml.safe_dump(PLATFORM))
    fixed["generate"]["vhdl"] |= {"rom_external": True, "ram_external": False}
    text = _map_package(tmp_path, fixed)
    _has(
        text,
        "constant FLASH_ON_BUS        : boolean  := true;",
        "constant RAM_ON_BUS          : boolean  := false;",
    )


def test_a_peripheral_over_a_region_is_rejected(tmp_path: Path) -> None:
    """A window that takes bytes of the RAM is an error (V-P5)."""
    bad = yaml.safe_load(yaml.safe_dump(PLATFORM))
    bad["peripherals"] = [{"name": "UART", "base": "0x10000", "size": "16"}]
    with pytest.raises(ValueError, match="V-P5 peripheral UART and RAM"):
        render_all(_write(tmp_path, bad), tmp_path)


def test_a_removed_window_key_is_rejected(tmp_path: Path) -> None:
    """`ext_base` and `periph_base` no longer exist (V-P6)."""
    bad = yaml.safe_load(yaml.safe_dump(PLATFORM))
    bad["generate"]["vhdl"] |= {"ext_base": "0x40000000"}
    with pytest.raises(ValueError, match="V-P6 ext_base"):
        render_all(_write(tmp_path, bad), tmp_path)


