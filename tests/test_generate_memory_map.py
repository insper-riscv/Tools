def _matrix(root: Path) -> None:
    """Write a profile spec with both bases and the M extension."""
    spec = {
        "bases": [
            {"name": "rv32i", "generics": {"num_regs": 32}},
            {"name": "rv32e", "generics": {"num_regs": 16}},
        ],
        "extensions": [{"name": "M", "generic": "has_m", "base_letter": "m"}],
    }
    (root / "matrix.yaml").write_text(yaml.safe_dump(spec))


def test_the_profile_gives_the_registers_and_the_switches(
    tmp_path: Path,
) -> None:
    """The package has `HAS_E` and one `HAS_*` per extension."""
    _matrix(tmp_path)
    small = _profiled("rv32em")
    text = _map_package(tmp_path, small)
    _has(
        text,
        "constant IS_E                : boolean  := true;",
        "constant HAS_M               : boolean  := true;",
    )
    set_override("rv32i")
    files = render_all(_write(tmp_path, small), tmp_path)
    set_override(None)
    text = files[tmp_path / "out/map_pkg.vhd"]
    _has(
        text,
        "constant IS_E                : boolean  := false;",
        "constant HAS_M               : boolean  := false;",
    )


def test_the_profile_flag_reaches_the_generated_package(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """`--profile` on the command line picks the profile of the run."""
    _matrix(tmp_path)
    small = yaml.safe_load(yaml.safe_dump(PLATFORM))
    small |= {"profile": "rv32i", "profiles": "matrix.yaml"}
    _write(tmp_path, small)
    monkeypatch.setattr(
        sys,
        "argv",
        [
            "riscv-tools",
            "--root",
            str(tmp_path),
            "--profile",
            "rv32e",
            "generate-memory-map",
            "--platform",
            "platform.yaml",
        ],
    )
    try:
        cli.main()
    finally:
        set_override(None)
    text = (tmp_path / "out/map_pkg.vhd").read_text()
    check_in("constant IS_E                : boolean  := true;", text)


def test_extras_turn_on_what_the_matrix_omits(
    tmp_path: Path,
) -> None:
    """`extras` sets what the matrix omits; the rest is false."""
    _matrix(tmp_path)
    small = _profiled("rv32im", extras=["Zimop", "Zihintpause"])
    text = _map_package(tmp_path, small)
    _has(
        text,
        "constant HAS_ZIMOP           : boolean  := true;",
        "constant HAS_ZICOND          : boolean  := false;",
        "constant HAS_ZICSR           : boolean  := false;",
        "constant HAS_ZIHINTPAUSE     : boolean  := true;",
        "constant HAS_ZIHINTNTL       : boolean  := false;",
    )
    small["extras"] = ["AccessFaults"]
    text = _map_package(tmp_path, small)
    check_in("constant HAS_ACCESS_FAULTS   : boolean  := true;", text)


def _matrix_hpm(root: Path) -> None:
    """Write a profile spec with Zicsr and Zihpm."""
    spec = {
        "bases": [{"name": "rv32i", "generics": {"num_regs": 32}}],
        "extensions": [
            {"name": "Zicsr", "generic": "has_zicsr"},
            {
                "name": "Zihpm",
                "generic": "has_zihpm",
                "implies": ["has_zicsr"],
            },
        ],
        "mutually_exclusive": [["Zicsr", "Zihpm"]],
    }
    (root / "matrix.yaml").write_text(yaml.safe_dump(spec))


def test_sscofpmf_extra_needs_zihpm_and_interrupts(tmp_path: Path) -> None:
    """`Sscofpmf` needs Zihpm and Interrupts and sets `HAS_SSCOFPMF`."""
    _matrix_hpm(tmp_path)
    full = _profiled("rv32i_zihpm", extras=["Interrupts", "Sscofpmf"])
    text = _map_package(tmp_path, full)
    _has(
        text,
        "constant HAS_SSCOFPMF        : boolean  := true;",
        "constant HAS_ZIHPM           : boolean  := true;",
    )
    off = full | {"extras": ["Interrupts"]}
    text = _map_package(tmp_path, off)
    check_in("constant HAS_SSCOFPMF        : boolean  := false;", text)
    for extras, profile in (
        (["Sscofpmf"], "rv32i_zihpm"),
        (["Interrupts", "Sscofpmf"], "rv32i_zicsr"),
    ):
        bad = full | {"extras": extras, "profile": profile}
        with pytest.raises(ValueError, match="Sscofpmf"):
            render_all(_write(tmp_path, bad), tmp_path)


