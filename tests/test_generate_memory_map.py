"""Tests for the files generated from the memory map."""

import argparse
from pathlib import Path
from typing import Any

import pytest
import yaml

from riscv_tools import cli
from riscv_tools.memory_map import check_all, render_all, write_all

PLATFORM: dict[str, Any] = {
    "regions": [
        {"name": "BOOT_ROM", "base": "0x0", "size": "2K", "exec": True},
        {"name": "FLASH", "base": "0x800", "size": "30K", "exec": True},
        {"name": "RAM", "base": "0x8000", "size": "160K", "kind": "ram"},
    ],
    "reserved": {
        "stdout": {"base": "0x2FBE0", "size": "1K+8"},
        "tohost": {"base": "0x2FFE8", "size": "8"},
        "fromhost": {"base": "0x2FFF0", "size": "8"},
    },
    "boot": {"entry": "0x800", "wait_restart": "0x100"},
    "peripherals": [{"name": "UART", "base": "0xC0000000", "id": 4}],
    "generate": {
        "specs": {
            "path": "out/x.specs",
            "rom": "FLASH",
            "ram": "RAM",
            "ram_limit": "stdout",
        },
        "boot_ld": {"path": "out/boot.ld"},
        "runtime": {"path": "out/memory_map.h", "ram": "RAM"},
        "vhdl": {
            "path": "out/map_pkg.vhd",
            "package": "map_pkg",
            "rom": "FLASH",
            "ram": "RAM",
        },
    },
}


def _write(root: Path, platform: dict[str, Any] | None = None) -> Path:
    path = root / "platform.yaml"
    path.write_text(yaml.safe_dump(platform or PLATFORM, sort_keys=False))
    return path


def test_specs_carries_the_linker_flags_of_the_map(tmp_path: Path) -> None:
    """The specs file has the base and size of the ROM and the RAM."""
    files = render_all(_write(tmp_path), tmp_path)
    text = files[tmp_path / "out/x.specs"]
    assert "--defsym=__flash=0x800 --defsym=__flash_size=0x7800" in text
    assert "--defsym=__ram=0x8000 --defsym=__ram_size=0x27BE0" in text
    assert "rv32_wait_restart=0x100" in text
    assert text.startswith("# Generated by `riscv-tools")


def test_boot_linker_script_has_the_boot_region(tmp_path: Path) -> None:
    """The boot linker script has the boot region and the restart."""
    files = render_all(_write(tmp_path), tmp_path)
    text = files[tmp_path / "out/boot.ld"]
    assert "ORIGIN = 0x0, LENGTH = 0x800" in text
    assert "RESET_RESERVED = 0x100;" in text


def test_vhdl_package_has_the_generics_in_kib(tmp_path: Path) -> None:
    """The VHDL package has the core generics and the peripherals."""
    files = render_all(_write(tmp_path), tmp_path)
    text = files[tmp_path / "out/map_pkg.vhd"]
    assert "constant BOOT_ROM_BITS       : natural  := 11;" in text
    assert "constant BOOT_ROM_SIZE_BYTES : positive := 2048;" in text
    assert "constant ROM_BASE_KIB        : natural  := 2;" in text
    assert "constant ROM_END_KIB         : natural  := 32;" in text
    assert "constant ROM_STORAGE_BYTES   : positive := 32768;" in text
    assert "constant RAM_BASE_KIB        : natural  := 32;" in text
    assert "constant RAM_END_KIB         : natural  := 192;" in text
    assert "constant RAM_STORAGE_BYTES   : positive := 262144;" in text
    assert "constant RAM_LAST_PAGE       :" in text
    assert 'x"0002F"' in text
    assert "constant EXT_BASE_KIB        : natural  := 2097152;" in text
    assert "constant PERIPH_BASE_KIB     : natural  := 2097152;" in text
    assert (
        'constant UART_BASE : std_logic_vector(31 downto 0) := x"C0000000"'
        in text
    )
    assert "constant UART_ID   : natural := 4;" in text
    assert "EXTERNAL" not in text


def test_write_then_check_passes_and_a_change_is_caught(
    tmp_path: Path,
) -> None:
    """A written set checks clean, and an edited file is reported."""
    platform = _write(tmp_path)
    written = write_all(platform, tmp_path)
    assert len(written) == 4
    count, problems = check_all(platform, tmp_path)
    assert (count, problems) == (4, [])
    (tmp_path / "out/boot.ld").write_text("hand edited\n")
    (tmp_path / "out/x.specs").unlink()
    _, problems = check_all(platform, tmp_path)
    details = sorted(p.detail for p in problems)
    assert details == ["missing", "out of date"]


def test_an_address_that_is_not_a_whole_kib_is_rejected(
    tmp_path: Path,
) -> None:
    """The core's generics are in KiB, so a ragged end is an error."""
    bad = yaml.safe_load(yaml.safe_dump(PLATFORM))
    bad["regions"][1]["size"] = "0x7A0"
    with pytest.raises(ValueError, match="multiple of 1 KiB"):
        render_all(_write(tmp_path, bad), tmp_path)


def test_an_inconsistent_map_is_not_generated(tmp_path: Path) -> None:
    """Overlapping regions stop the generation."""
    bad = yaml.safe_load(yaml.safe_dump(PLATFORM))
    bad["regions"][2]["base"] = "0x1000"
    with pytest.raises(ValueError, match="overlap"):
        render_all(_write(tmp_path, bad), tmp_path)


def test_the_command_writes_and_checks(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """The subcommand writes the files and `--check` then passes."""
    _write(tmp_path)
    args = argparse.Namespace(
        platform="platform.yaml", check=False, root=str(tmp_path), config=None
    )
    cli.cmd_generate_memory_map(args)
    assert "generated: out/x.specs" in capsys.readouterr().out
    args.check = True
    cli.cmd_generate_memory_map(args)
    assert "generated files OK: 4" in capsys.readouterr().out
    (tmp_path / "out/map_pkg.vhd").write_text("old\n")
    with pytest.raises(SystemExit) as stop:
        cli.cmd_generate_memory_map(args)
    assert stop.value.code == 1


def test_the_external_flags_appear_when_the_platform_fixes_them(
    tmp_path: Path,
) -> None:
    """`rom_external` and `ram_external` become constants when given."""
    fixed = yaml.safe_load(yaml.safe_dump(PLATFORM))
    fixed["generate"]["vhdl"] |= {"rom_external": True, "ram_external": False}
    files = render_all(_write(tmp_path, fixed), tmp_path)
    text = files[tmp_path / "out/map_pkg.vhd"]
    assert "constant ROM_EXTERNAL        : boolean  := true;" in text
    assert "constant RAM_EXTERNAL        : boolean  := false;" in text


def test_a_region_above_the_peripheral_window_is_rejected(
    tmp_path: Path,
) -> None:
    """A RAM above the lower 2 GiB is an error."""
    bad = yaml.safe_load(yaml.safe_dump(PLATFORM))
    bad["regions"][2] |= {"base": "0x7FFF8000", "size": "64K"}
    bad["reserved"] = {}
    with pytest.raises(ValueError, match="peripheral window"):
        render_all(_write(tmp_path, bad), tmp_path)


def test_the_window_can_be_moved_by_the_platform(tmp_path: Path) -> None:
    """A platform may name its own window bases in the VHDL section."""
    moved = yaml.safe_load(yaml.safe_dump(PLATFORM))
    moved["generate"]["vhdl"] |= {
        "ext_base": "0x40000000",
        "periph_base": "0x80000000",
    }
    files = render_all(_write(tmp_path, moved), tmp_path)
    text = files[tmp_path / "out/map_pkg.vhd"]
    assert "constant EXT_BASE_KIB        : natural  := 1048576;" in text


def test_runtime_header_has_the_shared_addresses(tmp_path: Path) -> None:
    """The header has the RAM end, tohost, fromhost and stdout."""
    files = render_all(_write(tmp_path), tmp_path)
    text = files[tmp_path / "out/memory_map.h"]
    assert "#define RV32_RAM_END RV32_ADDRESS(0x00030000)" in text
    assert "#define RV32_TOHOST_ADDR RV32_ADDRESS(0x0002FFE8)" in text
    assert "#define RV32_FROMHOST_ADDR RV32_ADDRESS(0x0002FFF0)" in text
    assert "#define RV32_STDOUT_BASE RV32_ADDRESS(0x0002FBE0)" in text
    assert "#ifdef __ASSEMBLER__" in text
