"""Tests for the C++ files generated from the memory map."""

from pathlib import Path
from typing import Any

import pytest
from support import (
    MAP_REGIONS,
    MAP_RESERVED,
    check,
    check_equal,
    check_in,
    check_not_in,
    dump_platform,
)

from riscv_tools.memory_map import check_all, render_all, write_all
from riscv_tools.memory_map.core import load_platform
from riscv_tools.memory_map.generate import render_specs
from riscv_tools.memory_map.symbol_table import symbol_table

SPECS: dict[str, Any] = {
    "path": "out/x.specs",
    "rom": "FLASH",
    "ram": "RAM",
    "ram_limit": "stdout",
}


def _platform(**generate: Any) -> dict[str, Any]:
    return {
        "regions": MAP_REGIONS,
        "reserved": MAP_RESERVED,
        "boot": {"entry": "0x800", "wait_restart": "0x100"},
        "peripherals": [{"name": "UART", "base": "0xC0000000", "size": "16"}],
        "generate": generate,
    }


def _render(tmp_path: Path, **generate: Any) -> dict[Path, str]:
    path = tmp_path / "platform.yaml"
    path.write_text(dump_platform(_platform(**generate)))
    return render_all(path, tmp_path)


def test_a_c_specs_file_is_the_same_as_before(tmp_path: Path) -> None:
    """Without `cxx` the specs file has no C++ object and no endfile."""
    text = _render(tmp_path, specs=SPECS)[tmp_path / "out/x.specs"]
    check(text.endswith("*startfile:\ncrt0-hosted%O%s\n"))
    check_not_in("crtbegin", text)
    check_not_in("*endfile", text)
    check_not_in("self_spec", text)


def test_cxx_false_is_the_c_specs_file(tmp_path: Path) -> None:
    """An explicit `cxx: false` changes nothing."""
    plain = _render(tmp_path, specs=SPECS)[tmp_path / "out/x.specs"]
    off = _render(tmp_path, specs={**SPECS, "cxx": False})[
        tmp_path / "out/x.specs"
    ]
    check_equal(off, plain)


def test_cxx_specs_register_the_unwind_frames(tmp_path: Path) -> None:
    """The start and end objects of the GCC join the link."""
    text = _render(tmp_path, specs={**SPECS, "cxx": True})[
        tmp_path / "out/x.specs"
    ]
    check_in("*startfile:\ncrt0-hosted%O%s crtbegin%O%s\n", text)
    check_in("*endfile:\ncrtend%O%s\n", text)
    # The crt0 is picked outright: `--crt0=` of picolibc.specs is gone.
    check_not_in("--crt0", text)


def test_cxx_specs_pick_the_cpp_linker_script(tmp_path: Path) -> None:
    """`picolibcpp.ld` is the default script, unless `-T` is given."""
    text = _render(tmp_path, specs={**SPECS, "cxx": True})[
        tmp_path / "out/x.specs"
    ]
    check_in("%rename self_spec rv32imfpga_self_spec\n", text)
    check_in(
        "*self_spec:\n%(rv32imfpga_self_spec) %{!T:-T picolibcpp.ld}\n",
        text,
    )


def test_cxx_specs_keep_the_linker_flags_of_the_map(tmp_path: Path) -> None:
    """The base and size of the memories are in the C++ file as well."""
    text = _render(tmp_path, specs={**SPECS, "cxx": True})[
        tmp_path / "out/x.specs"
    ]
    check_in("--defsym=__flash=0x800 --defsym=__flash_size=0x7800", text)
    check_in("--defsym=__ram=0x8000", text)
    check_in("%include <picolibc.specs>", text)


def test_cxx_must_be_a_boolean(tmp_path: Path) -> None:
    """A string is not a switch."""
    with pytest.raises(ValueError, match="true or false"):
        _render(tmp_path, specs={**SPECS, "cxx": "yes"})


def test_a_bank_spec_entry_can_ask_for_cxx(tmp_path: Path) -> None:
    """`cxx` works in any specs entry, `bank_specs` ones included."""
    path = tmp_path / "platform.yaml"
    path.write_text(dump_platform(_platform(specs=SPECS)))
    table = symbol_table(load_platform(path))

    text = render_specs({**SPECS, "cxx": True}, table, "platform.yaml")

    check_in("crtbegin%O%s", text)


def test_syscalls_are_the_stubs_the_libstdcxx_needs(tmp_path: Path) -> None:
    """Four functions, each failing with ENOSYS."""
    files = _render(
        tmp_path,
        specs={**SPECS, "cxx": True},
        syscalls={"path": "out/syscalls.c"},
    )
    text = files[tmp_path / "out/syscalls.c"]
    for signature in (
        "int getentropy(void *buffer, size_t length)",
        "ssize_t read(int fd, void *buffer, size_t length)",
        "int open(const char *path, int flags, ...)",
        "int close(int fd)",
    ):
        check_in(signature, text)
    check_equal(text.count("errno = ENOSYS;"), 4)
    check_equal(text.count("return -1;"), 4)
    check(text.startswith("/* Generated by `riscv-tools"))


def test_syscalls_do_not_clash_with_the_other_runtime_files(
    tmp_path: Path,
) -> None:
    """They define none of what `_exit.c` and `stdio.c` define."""
    text = _render(
        tmp_path,
        specs={**SPECS, "cxx": True},
        syscalls={"path": "out/syscalls.c"},
    )[tmp_path / "out/syscalls.c"]
    for symbol in ("_exit", "stdout", "stderr", "write", "putc", "getc"):
        check_not_in(f" {symbol}(", text)
        check_not_in(f"*{symbol}", text)


def test_syscalls_are_for_cxx_only(tmp_path: Path) -> None:
    """A C platform has no use for them: asking is an error."""
    with pytest.raises(ValueError, match=r"generate\.syscalls is for C\+\+"):
        _render(tmp_path, specs=SPECS, syscalls={"path": "out/syscalls.c"})


def test_the_cxx_files_are_written_and_checked(tmp_path: Path) -> None:
    """`write_all` writes them and `check_all` finds them current."""
    path = tmp_path / "platform.yaml"
    path.write_text(
        dump_platform(
            _platform(
                specs={**SPECS, "cxx": True},
                syscalls={"path": "out/syscalls.c"},
            )
        )
    )

    written = write_all(path, tmp_path)
    count, problems = check_all(path, tmp_path)

    check_in(tmp_path / "out/syscalls.c", written)
    check_equal(count, 2)
    check_equal(len(problems), 0)
